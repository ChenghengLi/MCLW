def run_comparison_experiment(config: dict, results_dir: Path, quick: bool = False):
    """Run head-to-head comparison experiment."""
    print("\n" + "="*60)
    print("EXPERIMENT 4: Perplexity vs LTW Comparison")
    print("="*60)
    
    # Prepare dataset
    texts = AI_LIKE_TEXTS + HUMAN_LIKE_TEXTS
    labels = [True] * len(AI_LIKE_TEXTS) + [False] * len(HUMAN_LIKE_TEXTS)  # True = "should detect"
    
    print(f"\nDataset: {len(AI_LIKE_TEXTS)} AI-like texts, {len(HUMAN_LIKE_TEXTS)} human-like texts")
    
    # Initialize detectors
    print("\n[1/4] Initializing detectors...")
    
    ltw_detector = LTWWatermarker(
        secret_key=config['watermark']['secret_key'],
        rotation_strength=config['watermark']['rotation_strength'],
        detection_threshold=config['watermark']['detection_threshold'],
        use_differential_scoring=config['watermark']['use_differential_scoring'],
        unit=config['watermark']['unit']
    )
    
    print("  Loading perplexity model (this may take a moment)...")
    try:
        ppl_detector = PerplexityDetector(
            model_name=config.get('perplexity', {}).get('model_name', 'gpt2'),
            perplexity_threshold=config.get('perplexity', {}).get('threshold', 30.0),
        )
        perplexity_available = True
    except Exception as e:
        print(f"  Warning: Could not load perplexity model: {e}")
        print("  Continuing with LTW only...")
        perplexity_available = False
    
    # Collect scores
    print("\n[2/4] Running detection on all texts...")
    
    ltw_scores = []
    ltw_predictions = []
    ppl_scores = []
    ppl_predictions = []
    
    for i, text in enumerate(tqdm(texts, desc="Processing")):
        # LTW detection
        ltw_result = ltw_detector.detect(text)
        ltw_scores.append(ltw_result.differential_score)
        ltw_predictions.append(ltw_result.is_watermarked)
        
        # Perplexity detection
        if perplexity_available:
            ppl_result = ppl_detector.detect(text)
            # Invert perplexity (lower = more AI-like, so negate for ROC)
            ppl_scores.append(-ppl_result.perplexity)
            ppl_predictions.append(ppl_result.is_ai_generated)
    
    # Calculate metrics
    print("\n[3/4] Calculating metrics...")
    
    ltw_stats = ltw_detector.get_detection_stats(texts, labels)
    
    results = {
        'ltw': {
            'scores': ltw_scores,
            'predictions': ltw_predictions,
            'metrics': ltw_stats,
        }
    }
    
    if perplexity_available:
        ppl_stats = ppl_detector.get_detection_stats(texts, labels)
        results['perplexity'] = {
            'scores': ppl_scores,
            'predictions': ppl_predictions,
            'metrics': ppl_stats,
        }
    
    # Print comparison table
    print("\n" + "-"*70)
    print(f"{'Metric':<20} {'LTW':<15} {'Perplexity':<15} {'Winner':<15}")
    print("-"*70)
    
    metrics_to_compare = ['accuracy', 'precision', 'recall', 'f1', 'fpr', 'tpr']
    
    for metric in metrics_to_compare:
        ltw_val = ltw_stats[metric]
        if perplexity_available:
            ppl_val = ppl_stats[metric]
            # For FPR, lower is better
            if metric == 'fpr':
                winner = 'LTW' if ltw_val < ppl_val else 'Perplexity' if ppl_val < ltw_val else 'Tie'
            else:
                winner = 'LTW' if ltw_val > ppl_val else 'Perplexity' if ppl_val > ltw_val else 'Tie'
            print(f"{metric:<20} {ltw_val:<15.4f} {ppl_val:<15.4f} {winner:<15}")
        else:
            print(f"{metric:<20} {ltw_val:<15.4f} {'N/A':<15} {'N/A':<15}")
    
    print("-"*70)
    
    # Visualizations
    print("\n[4/4] Generating visualizations...")
    
    # ROC comparison
    if perplexity_available:
        methods = {
            'LTW (Differential Score)': (labels, ltw_scores),
            'Perplexity (Negative)': (labels, ppl_scores),
        }
        fig = plot_roc_comparison(
            methods,
            title="ROC Curve Comparison: LTW vs Perplexity",
            save_path=str(results_dir / 'exp4_roc_comparison.png')
        )
        print(f"  Saved: {results_dir / 'exp4_roc_comparison.png'}")
    else:
        from ltw_watermark.analysis import plot_roc_curve
        _, fig = plot_roc_curve(
            labels, ltw_scores,
            title="LTW ROC Curve",
            save_path=str(results_dir / 'exp4_ltw_roc.png')
        )
        print(f"  Saved: {results_dir / 'exp4_ltw_roc.png'}")
    
    # Confusion matrices
    fig = plot_confusion_matrix(
        labels, ltw_predictions,
        title="LTW Confusion Matrix",
        save_path=str(results_dir / 'exp4_ltw_confusion.png')
    )
    print(f"  Saved: {results_dir / 'exp4_ltw_confusion.png'}")
    
    # Score distributions
    fig, axes = plt.subplots(1, 2 if perplexity_available else 1, figsize=(14 if perplexity_available else 8, 5))
    
    if not perplexity_available:
        axes = [axes]
    
    # LTW scores
    ax = axes[0]
    ai_ltw = [s for s, l in zip(ltw_scores, labels) if l]
    human_ltw = [s for s, l in zip(ltw_scores, labels) if not l]
    ax.hist(human_ltw, bins=15, alpha=0.6, label='Human-like', color='blue', density=True)
    ax.hist(ai_ltw, bins=15, alpha=0.6, label='AI-like', color='red', density=True)
    ax.axvline(x=config['watermark']['detection_threshold'], color='green', linestyle='--', 
               label=f'Threshold ({config["watermark"]["detection_threshold"]})')
    ax.set_xlabel('LTW Differential Score')
    ax.set_ylabel('Density')
    ax.set_title('LTW Score Distribution')
    ax.legend()
    
    # Perplexity scores
    if perplexity_available:
        ax = axes[1]
        ai_ppl = [-s for s, l in zip(ppl_scores, labels) if l]  # Undo negation
        human_ppl = [-s for s, l in zip(ppl_scores, labels) if not l]
        ax.hist(human_ppl, bins=15, alpha=0.6, label='Human-like', color='blue', density=True)
        ax.hist(ai_ppl, bins=15, alpha=0.6, label='AI-like', color='red', density=True)
        ax.axvline(x=config.get('perplexity', {}).get('threshold', 30.0), color='green', linestyle='--', 
                   label=f'Threshold')
        ax.set_xlabel('Perplexity')
        ax.set_ylabel('Density')
        ax.set_title('Perplexity Distribution')
        ax.legend()
    
    plt.tight_layout()
    fig.savefig(results_dir / 'exp4_score_distributions.png', dpi=150, bbox_inches='tight')
    print(f"  Saved: {results_dir / 'exp4_score_distributions.png'}")
    
    # Save results
    serializable_results = {
        'ltw': {
            'metrics': ltw_stats,
            'score_stats': {
                'mean': float(np.mean(ltw_scores)),
                'std': float(np.std(ltw_scores)),
            }
        }
    }
    if perplexity_available:
        serializable_results['perplexity'] = {
            'metrics': ppl_stats,
            'score_stats': {
                'mean': float(np.mean([-s for s in ppl_scores])),
                'std': float(np.std([-s for s in ppl_scores])),
            }
        }
    
    with open(results_dir / 'exp4_results.json', 'w') as f:
        json.dump(serializable_results, f, indent=2)
    print(f"  Saved: {results_dir / 'exp4_results.json'}")
    
    return results


def main():
    parser = argparse.ArgumentParser(description="Experiment 4: Perplexity vs LTW Comparison")
    parser.add_argument("--config", type=str, default="config.yaml")
    parser.add_argument("--quick", action="store_true")
    args = parser.parse_args()
    
    config_path = Path(__file__).parent.parent / args.config
    if config_path.exists():
        with open(config_path, 'r') as f:
            config = yaml.safe_load(f)
    else:
        config = {
            'watermark': {
                'secret_key': 'test-secret-key',
                'rotation_strength': 0.3,
                'detection_threshold': 0.1,
                'use_differential_scoring': True,
                'unit': 'sentence'
            },
            'perplexity': {
                'model_name': 'gpt2',
                'threshold': 30.0,
            }
        }
    
    results_dir = Path(__file__).parent.parent / "results" / "exp4"
    results_dir.mkdir(parents=True, exist_ok=True)
    
    results = run_comparison_experiment(config, results_dir, args.quick)
    
    print("\n" + "="*60)
    print("EXPERIMENT 4 COMPLETE")
    print("="*60)
    
    # Summary
    ltw_f1 = results['ltw']['metrics']['f1']
    print(f"\nLTW F1 Score: {ltw_f1:.3f}")
    if 'perplexity' in results:
        ppl_f1 = results['perplexity']['metrics']['f1']
        print(f"Perplexity F1 Score: {ppl_f1:.3f}")
        if ltw_f1 > ppl_f1:
            print("\n✓ LTW outperforms perplexity-based detection on this dataset!")
        else:
            print("\n📊 Perplexity performed better on this dataset. Consider parameter tuning.")


if __name__ == "__main__":
    main()
